/*
 * Minimal SSD1306 128x64 I2C driver, built on the bare-metal I2C1 driver
 * in wokwi_i2c.c (see that file's header comment for why HAL_I2C is not
 * used here). Text-only: a local framebuffer is drawn into with a 5x7
 * font and pushed to the panel a page at a time.
 */

#include "ssd1306.h"
#include "wokwi_i2c.h"
#include <string.h>

static uint8_t framebuffer[SSD1306_PAGES][SSD1306_WIDTH];
static uint8_t cursor_page = 0;
static uint8_t cursor_col_px = 0;

/* Diagnostic: incremented every time an I2C write to the OLED fails
 * (NACK or timeout). Read from main.cpp after SSD1306_Init() to confirm
 * the bus is actually working. Should be 0 on a healthy bus. */
